// Shared logic for submitting a single local record to the cloud.
import { uploadAllPhotos, uploadPhotoToS3 } from './uploadPhoto';
import { authFetch, getUser } from './session';
import { API_BASE } from '../config';

const API_URL = `${API_BASE}/plants`;

// Remembers the photo links already uploaded for each record (in memory
// only), so a retry doesn't upload the same photos to S3 again.
const uploadedPhotoCache = {};

// Empty text fields become null instead of 0 or an empty string.
const toNumberOrNull = (value) =>
  value === '' || value === null || value === undefined ? null : Number(value);

export async function syncRecordToCloud(record) {
  let photoUrls = uploadedPhotoCache[record.id];

  if (!photoUrls) {
    photoUrls =
      record.photos?.length > 0
        ? await uploadAllPhotos(record.photos, record)
        : [];
    uploadedPhotoCache[record.id] = photoUrls;
  }

  // last_edit is generated by the backend and returned to the app; do not
  // send a phone clock value that could overwrite the server's audit time.
  const body = {
    scientificName: record.scientificName,
    commonName: record.commonName,
    family: record.family,
    genus: record.genus || null,
    species: record.species || null,
    latitude: toNumberOrNull(record.latitude),
    longitude: toNumberOrNull(record.longitude),
    height: toNumberOrNull(record.height),
    diameter_cm: toNumberOrNull(record.diameter),
    notes: record.notes,
    imageUrl: photoUrls[0] || null,
    // The backend reads this one. It saves every photo link.
    imageUrls: photoUrls,
    // The botanist who is logged in, so the web shows who submitted it.
    // The account that MADE the record, not whoever happens to be logged in
    // when it is finally sent.
    submitted_by: record.ownerId ?? getUser()?.id ?? null,
  };

  const response = await authFetch(API_URL, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  });

  const text = await response.text();
  let data;
  try {
    data = JSON.parse(text);
  } catch (e) {
    console.log('Server replied with non-JSON:', response.status, text.slice(0, 300));
    const notJson = new Error(`Server error ${response.status} (not JSON)`);
    notJson.status = response.status;
    throw notJson;
  }

  if (!response.ok) {
    const failed = new Error(data.error || `Failed to submit plant record (${response.status}).`);
    failed.status = response.status;
    throw failed;
  }

  return data;
}

// ---------------------------------------------------------------------------
// Editing a record that is already in the cloud.
// ---------------------------------------------------------------------------

// Photos taken for an edit that were already uploaded (by their place on the
// phone), so a retry never uploads the same photo twice.
const uploadedEditPhotos = {};

const isOnlineLink = (uri) => /^https?:\/\//i.test(String(uri || ''));

async function sendJson(url, method, body) {
  const response = await authFetch(url, {
    method,
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  });

  const text = await response.text();
  let data = null;

  try {
    data = text ? JSON.parse(text) : null;
  } catch (e) {
    // The reply was not JSON.
  }

  if (!response.ok) {
    const error = new Error(
      (data && data.error) || `Server error ${response.status}.`
    );
    error.status = response.status;
    throw error;
  }

  return data || {};
}

// Sends an edited record to the cloud.
//  1. New photos from the phone are uploaded. Photos that are already online
//     are kept as they are.
//  2. The record is set back to Pending (this also clears the rejection note).
//     This is done BEFORE saving the edit, so the history entry that the edit
//     creates is saved as Pending.
//  3. The changes are saved.
// If anything fails, nothing is lost: the phone keeps the edit and tries again.
export async function syncUpdateToCloud(record) {
  const serverId = record.serverId;

  if (!serverId) {
    throw new Error('This plant record is not in the cloud yet.');
  }

  const photoUrls = [];

  for (const uri of record.photos || []) {
    if (isOnlineLink(uri)) {
      photoUrls.push(uri);
      continue;
    }

    if (!uploadedEditPhotos[uri]) {
      uploadedEditPhotos[uri] = await uploadPhotoToS3(uri, record);
    }

    photoUrls.push(uploadedEditPhotos[uri]);
  }

  await sendJson(`${API_URL}/${serverId}/status`, 'PATCH', {
    status: 'Pending',
    reason: null,
  });

  return sendJson(`${API_URL}/${serverId}`, 'PUT', {
    scientificName: record.scientificName,
    commonName: record.commonName,
    family: record.family,
    genus: record.genus || null,
    species: record.species || null,
    latitude: toNumberOrNull(record.latitude),
    longitude: toNumberOrNull(record.longitude),
    height: toNumberOrNull(record.height),
    diameter_cm: toNumberOrNull(record.diameter),
    notes: record.notes,
    imageUrls: photoUrls,
    change_summary: 'Edited in the mobile app. Sent back for review.',
  });
}
